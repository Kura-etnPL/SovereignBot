  let _locale = "en";

  function resolveLocale(setting, systemLocale) {
    if (setting === "zh-CN") return "zh-CN";
    if (setting === "en") return "en";
    const sys = String(systemLocale ?? "");
    if (/^zh/i.test(sys)) return "zh-CN";
    return "en";
  }

  function setLocale(locale) {
    const next = locale === "zh-CN" ? "zh-CN" : "en";
    _locale = next;
    try {
      if (typeof document !== "undefined" && document.documentElement) {
        document.documentElement.lang = next;
      }
    } catch {}
    return next;
  }

  function currentLocale() {
    return _locale;
  }

  function t(key, params) {
    const table = translations[_locale] ?? translations.en;
    let value = table[key];
    if (value === undefined) {
      // In development / testing, surface missing keys explicitly rather than silently falling back
      return `[[missing:${key}]]`;
    }
    if (params && typeof params === "object") {
      for (const [k, v] of Object.entries(params)) {
        value = value.replaceAll(`{${k}}`, String(v));
      }
    }
    return value;
  }

